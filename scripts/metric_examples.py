"""Run example MetricFlow queries against the semantic layer and save them to docs/metric_examples.md."""

from __future__ import annotations

import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path

MF = str(Path(sys.executable).with_name("mf"))
OUT = Path("docs/metric_examples.md")

EXAMPLES = [
    (
        "30+ DPD delinquency rate by product by month (2025)",
        [
            "--metrics", "delinquency_rate_30plus",
            "--group-by", "metric_time__month,account_month__product_name",
            "--start-time", "2025-01-01",
            "--order", "metric_time__month,account_month__product_name",
        ],
    ),
    (
        "Forward roll rate by prior-month delinquency bucket (all months pooled)",
        [
            "--metrics", "roll_rate,roll_eligible_accounts",
            "--group-by", "account_month__prior_delinquency_bucket",
            "--where", "{{ Dimension('account_month__prior_delinquency_bucket') }} is not null",
            "--order", "-roll_eligible_accounts",
        ],
    ),
    (
        "Monthly portfolio scorecard (2025): active accounts, utilization, annualized net charge-off rate",
        [
            "--metrics", "active_accounts,utilization_rate,net_charge_off_rate",
            "--group-by", "metric_time__month",
            "--start-time", "2025-01-01",
            "--end-time", "2025-12-31",
            "--order", "metric_time__month",
        ],
    ),
]


def main() -> None:
    sections = [
        "# Semantic layer - example metric queries",
        "",
        "Generated by `make metrics` (scripts/metric_examples.py) with "
        "[MetricFlow](https://docs.getdbt.com/docs/build/about-metricflow) against the local DuckDB warehouse. "
        "Metric definitions live in `models/semantic/_semantic_models.yml`.",
        "",
        "> All data is synthetic. Values reflect the generator's assumptions, not real-world portfolio performance.",
        "",
        f"_Generated {datetime.now(timezone.utc):%Y-%m-%d %H:%M} UTC._",
    ]
    for title, args in EXAMPLES:
        cmd = [MF, "query", *args, "--decimals", "4", "--quiet"]
        result = subprocess.run(cmd, capture_output=True, text=True)
        if result.returncode != 0:
            sys.exit(f"mf query failed for '{title}':\n{result.stdout}\n{result.stderr}")
        shown = "mf query " + " ".join(f'"{a}"' if any(ch in a for ch in " {'") else a for a in args)
        sections += ["", f"## {title}", "", "```bash", shown, "```", "", "```text", result.stdout.strip(), "```"]
        print(f"  ok: {title}")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(sections) + "\n")
    print(f"Wrote {OUT}")


if __name__ == "__main__":
    main()
